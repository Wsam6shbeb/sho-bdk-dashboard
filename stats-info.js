  function decorateToolbar() {
    Object.entries(TOOLBAR).forEach(([id, value]) => {
      const select = document.getElementById(id);
      if (!select || !select.parentNode || select.parentNode.classList.contains("stats-select-row")) return;
      const wrap = document.createElement("div");
      wrap.className = "stats-select-row";
      select.parentNode.insertBefore(wrap, select);
      wrap.append(select, makeButton({ title: value[0], text: value[1] }));
    });
  }

  decorateToolbar();
