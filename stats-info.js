  // ------------------------------------------------------------ أدوات
  function textOf(element) {
    const first = element.firstChild;
    const text = first && first.nodeType === 3 ? first.data : element.textContent;
    return String(text || "").trim();
  }

  // مطابقة تامة أولاً، ثم بالبداية (لعناوين لها لاحقة ديناميكية مثل المبلغ بين قوسين).
  function lookup(map, text) {
    let key = Object.prototype.hasOwnProperty.call(map, text) ? text : null;
    if (key === null) key = Object.keys(map).find((candidate) => text.startsWith(candidate)) || null;
    if (key === null) return null;
    const value = map[key];
    return Array.isArray(value) ? { title: value[0], text: value[1] } : { title: key, text: value };
  }

  function makeButton(entry) {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "setting-info-button";
    button.textContent = "i";
    button.setAttribute("aria-label", "معلومات عن " + entry.title);
    button.setAttribute("data-info-title", entry.title);
    button.setAttribute("data-info", entry.text);
    return button;
  }

  function attach(element, entry) {
    if (!entry || element.classList.contains("has-info")) return;
    element.classList.add("has-info");
    element.appendChild(makeButton(entry));
  }

  // ------------------------------------------------------------ التزيين
  function decorate() {
    content.querySelectorAll(".stats-kpi > span").forEach((element) => attach(element, lookup(KPI, textOf(element))));

    content.querySelectorAll(".stats-panel").forEach((panel) => {
      const heading = panel.querySelector(":scope > h3");
      if (!heading) return;
      const title = textOf(heading);
      attach(heading, lookup(PANELS, title));

      panel.querySelectorAll("th").forEach((element) => attach(element, lookup(HEADERS, textOf(element))));

      if (title === "نتائج الطلبات") {
        panel.querySelectorAll(".legend-row > span:first-of-type").forEach((element) => attach(element, lookup(LEGEND, textOf(element))));
      }
      if (title === "جودة تحليل الطلبات") {
        panel.querySelectorAll("tbody td:first-child").forEach((element) => attach(element, lookup(QUALITY_ROWS, textOf(element))));
      }
      if (title === "جاهزية مقدمي الخدمة") {
        panel.querySelectorAll("tbody td:first-child").forEach((element) => attach(element, lookup(READINESS_ROWS, textOf(element))));
      }
    });

    // قسم «الخدمات»: عناوينه ليست h3 مباشرة تحت اللوحة، فنعالجه هنا.
    content.querySelectorAll(".stats-services > h2, .stats-services .stats-subtitle").forEach((element) => attach(element, lookup(SERVICES, textOf(element))));
    content.querySelectorAll(".stats-services .stats-filter > span").forEach((element) => attach(element, lookup(FILTERS, textOf(element))));
    content.querySelectorAll(".stats-services th").forEach((element) => attach(element, lookup(HEADERS, textOf(element))));
  }

