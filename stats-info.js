  function textOf(element) {
    const first = element.firstChild;
    const text = first && first.nodeType === 3 ? first.data : element.textContent;
    return String(text || "").trim();
  }

  // مطابقة تامة أولاً، ثم بالبداية (لعناوين لها لاحقة ديناميكية مثل المبلغ بين قوسين).
  function lookup(map, text) {
    let key = Object.prototype.hasOwnProperty.call(map, text) ? text : null;
    if (key === null) key = Object.keys(map).find((candidate) => text.startsWith(candidate)) || null;
    if (key === null) return null;
    const value = map[key];
    return Array.isArray(value) ? { title: value[0], text: value[1] } : { title: key, text: value };
  }

  function makeButton(entry) {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "setting-info-button";
    button.textContent = "i";
    button.setAttribute("aria-label", "معلومات عن " + entry.title);
    button.setAttribute("data-info-title", entry.title);
    button.setAttribute("data-info", entry.text);
    return button;
  }

  function attach(element, entry) {
    if (!entry || element.classList.contains("has-info")) return;
    element.classList.add("has-info");
    element.appendChild(makeButton(entry));
  }

